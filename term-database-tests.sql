-- 回滾測試，不留下任何虛構會員、銀行或交易。
begin;
do $$
declare father uuid:=gen_random_uuid(); sister uuid:=gen_random_uuid(); stranger uuid:=gen_random_uuid();
 s jsonb; fid uuid; rid uuid; first_term uuid; second_term uuid; refused boolean;
 today date:=(now() at time zone 'Asia/Taipei')::date;
 mon date:=(date_trunc('month',now() at time zone 'Asia/Taipei')-interval '1 month')::date;
 val numeric; source_data jsonb;
begin
 insert into auth.users(id) values(father),(sister),(stranger);
 perform set_config('request.jwt.claim.sub',father::text,true);
 s:=public.fb_command('create','{"name":"定存回滾測試","capital":2000}');fid:=(s->'family'->>'id')::uuid;
 if (s->'family'->>'auto_rates')::boolean then raise exception '同步開關不應預設開啟';end if;
 perform set_config('request.jwt.claim.sub',sister::text,true);
 s:=public.fb_command('join',jsonb_build_object('code',s->'family'->>'code'));
 perform set_config('request.jwt.claim.sub',father::text,true);
 s:=public.fb_command('assign',jsonb_build_object('member',sister,'role','manager'));
 perform set_config('request.jwt.claim.sub',sister::text,true);
 s:=public.fb_command('request','{"kind":"deposit","amount":50000,"note":"測試存款"}');
 select id into rid from public.fb_requests where family=fid and status='pending';
 perform set_config('request.jwt.claim.sub',father::text,true);
 s:=public.fb_command('review',jsonb_build_object('id',rid,'decision','approve','date',today));
 perform set_config('request.jwt.claim.sub',sister::text,true);
 s:=public.fb_command('request','{"kind":"term_open","amount":40000,"months":3,"note":"測試定存"}');
 select id into rid from public.fb_requests where family=fid and status='pending';
 perform set_config('request.jwt.claim.sub',father::text,true);
 s:=public.fb_command('review',jsonb_build_object('id',rid,'decision','approve','date',today));
 select id into first_term from public.fb_term_deposits where family=fid;
 select sum(deposits) into val from public.fb_entries where family=fid;if val<>50000 then raise exception '轉存不應增加存款負債';end if;
 s:=public.fb_command('term_rate',jsonb_build_object('months',3,'rate',.025,'date',today));
 select rate into val from public.fb_term_deposits where id=first_term;if val<>.0129 then raise exception '既有定存利率被人工修改';end if;
 perform set_config('request.jwt.claim.sub',sister::text,true);
 refused:=false;begin perform public.fb_command('request','{"kind":"withdraw","amount":10001,"note":"超出活期"}');exception when others then refused:=true;end;
 if not refused then raise exception '定存本金可以直接提款';end if;
 s:=public.fb_command('request','{"kind":"withdraw","amount":10000,"note":"之後將被鎖定"}');
 select id into rid from public.fb_requests where family=fid and kind='withdraw' and status='pending';
 s:=public.fb_command('request','{"kind":"term_open","amount":10000,"months":1,"note":"第二筆定存"}');
 perform set_config('request.jwt.claim.sub',father::text,true);
 s:=public.fb_command('review',jsonb_build_object('id',(select id from public.fb_requests where family=fid and kind='term_open' and status='pending'),'decision','approve','date',today));
 select id into second_term from public.fb_term_deposits where family=fid and id<>first_term;
 refused:=false;begin perform public.fb_command('review',jsonb_build_object('id',rid,'decision','approve','date',today));exception when others then refused:=true;end;
 if not refused then raise exception '核准時沒有重新檢查可用活期';end if;
 s:=public.fb_command('review',jsonb_build_object('id',rid,'decision','reject'));
 source_data:=jsonb_build_object('source','臺灣銀行','source_url','https://rate.bot.com.tw/twd?Lang=zh-TW','source_date',today,'demand_rate',.009,
 'terms',jsonb_build_array(jsonb_build_object('months',1,'rate',.013),jsonb_build_object('months',3,'rate',.015),jsonb_build_object('months',6,'rate',.017),jsonb_build_object('months',12,'rate',.019)));
 refused:=false;begin perform public.fb_command('live_rate',source_data);exception when others then refused:=true;end;
 if not refused then raise exception '同步關閉仍可套用';end if;
 s:=public.fb_command('auto_rates','{"enabled":true}');
 refused:=false;begin perform public.fb_command('live_rate',jsonb_set(source_data,'source_date',to_jsonb((today-30)::text)));exception when others then refused:=true;end;
 if not refused then raise exception '過期牌告未阻擋';end if;
 s:=public.fb_command('live_rate',source_data);
 select rate into val from public.fb_term_deposits where id=first_term;if val<>.0129 then raise exception '同步改動了已開立定存';end if;
 select rate into val from public.fb_rates where family=fid and month=(date_trunc('month',today)+interval '1 month')::date;if val<>.009 then raise exception '活期未登記為次月生效';end if;
 perform set_config('request.jwt.claim.sub',sister::text,true);
 refused:=false;begin perform public.fb_command('auto_rates','{"enabled":false}');exception when others then refused:=true;end;
 if not refused then raise exception '孩子可修改同步開關';end if;
 -- 在回滾交易中種入跨月情境，驗證定存本金不重複算活期。
 update public.fb_families set opened=mon where id=fid;
 update public.fb_entries set date=mon where family=fid and kind in ('capital','deposit');
 update public.fb_entries set date=mon where family=fid and kind='term_open' and amount=40000;
 update public.fb_entries set date=mon+14 where family=fid and kind='term_open' and amount=10000;
 update public.fb_term_deposits set opened=mon,maturity=(mon+interval '1 month')::date where id=first_term;
 update public.fb_term_deposits set opened=mon+14,maturity=today+30 where id=second_term;
 insert into public.fb_rates values(fid,mon,.00825,'2026-10-14');
 perform set_config('request.jwt.claim.sub',father::text,true);
 s:=public.fb_command('close',jsonb_build_object('cash',52000,'month',to_char(mon,'YYYY-MM')));
 -- 前 14 天可用活期 10000 元，之後全為定存，月息四捨五入為 3 元。
 select balance into val from public.fb_accounts where family=fid and id='002';if val<>50003 then raise exception '活期與定存重複計息，餘額 %',val;end if;
 perform set_config('request.jwt.claim.sub',sister::text,true);
 s:=public.fb_command('request',jsonb_build_object('kind','term_redeem','amount',40000,'term_id',first_term,'note','到期轉回'));
 select id into rid from public.fb_requests where family=fid and status='pending';
 perform set_config('request.jwt.claim.sub',father::text,true);
 s:=public.fb_command('review',jsonb_build_object('id',rid,'decision','approve','date',today));
 select interest_paid into val from public.fb_term_deposits where id=first_term;
 if val<>round(40000*.0129*((mon+interval '1 month')::date-mon)/365) then raise exception '定存結清息不正確';end if;
 refused:=false;begin perform public.fb_command('review',jsonb_build_object('id',rid,'decision','approve','date',today));exception when others then refused:=true;end;
 if not refused then raise exception '可以重複結清定存';end if;
 perform set_config('request.jwt.claim.sub',sister::text,true);
 s:=public.fb_command('request',jsonb_build_object('kind','term_redeem','amount',10000,'term_id',second_term,'note','提前解約'));
 select id into rid from public.fb_requests where family=fid and status='pending';
 perform set_config('request.jwt.claim.sub',father::text,true);
 s:=public.fb_command('review',jsonb_build_object('id',rid,'decision','approve','date',today));
 select interest_paid into val from public.fb_term_deposits where id=second_term;if val<>0 then raise exception '提前解約應依教學規則不付息';end if;
 select sum(cash+loans-deposits-equity) into val from public.fb_entries where family=fid;if val<>0 then raise exception '銀行資產負債不平衡';end if;
 if has_function_privilege('authenticated','public.fb_command_v1(text,jsonb)','EXECUTE') or has_table_privilege('authenticated','public.fb_term_deposits','UPDATE') then raise exception '可繞過安全檢查';end if;
 perform set_config('request.jwt.claim.sub',stranger::text,true);
 s:=public.fb_command('state');if s is not null then raise exception '外家庭可看到定存';end if;
end $$;
select 'PASS：定存鎖定、人工與同步均不追溯、開關與角色、過期資料拒絕、次月活期、重複計息阻擋、到期與提前解約、會計與家庭隔離' as result;
rollback;
